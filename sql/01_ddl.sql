CREATE TABLE usuario (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 6 INCREMENT BY 1),
    email      VARCHAR2(254 CHAR) NOT NULL,
    senha_hash VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

CREATE TABLE pergunta (
    id_pergunta      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 6 INCREMENT BY 1),
    enunciado        VARCHAR2(500 CHAR) NOT NULL,
    resposta_correta CHAR(1 CHAR) NOT NULL,
    explicacao       VARCHAR2(2000 CHAR) NOT NULL,
    CONSTRAINT pk_pergunta PRIMARY KEY (id_pergunta),
    CONSTRAINT ck_pergunta_resposta CHECK (resposta_correta IN ('V', 'F', 'D'))
);

CREATE TABLE fonte (
    id_fonte    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 6 INCREMENT BY 1),
    titulo      VARCHAR2(200 CHAR) NOT NULL,
    instituicao VARCHAR2(150 CHAR) NOT NULL,
    url         VARCHAR2(1000 CHAR) NOT NULL,
    CONSTRAINT pk_fonte PRIMARY KEY (id_fonte),
    CONSTRAINT uq_fonte_url UNIQUE (url)
);

CREATE TABLE pergunta_fonte (
    id_pergunta NUMBER NOT NULL,
    id_fonte    NUMBER NOT NULL,
    CONSTRAINT pk_pergunta_fonte PRIMARY KEY (id_pergunta, id_fonte),
    CONSTRAINT fk_pf_pergunta FOREIGN KEY (id_pergunta)
        REFERENCES pergunta (id_pergunta),
    CONSTRAINT fk_pf_fonte FOREIGN KEY (id_fonte)
        REFERENCES fonte (id_fonte)
);

CREATE TABLE tentativa (
    id_tentativa       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 6 INCREMENT BY 1),
    id_usuario         NUMBER NOT NULL,
    id_pergunta        NUMBER NOT NULL,
    resposta_escolhida CHAR(1 CHAR) NOT NULL,
    respondido_em      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tentativa PRIMARY KEY (id_tentativa),
    CONSTRAINT fk_tentativa_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_tentativa_pergunta FOREIGN KEY (id_pergunta)
        REFERENCES pergunta (id_pergunta),
    CONSTRAINT ck_tentativa_resposta CHECK (resposta_escolhida IN ('V', 'F', 'D'))
);

-- Índices para as colunas estrangeiras consultadas com frequência.
CREATE INDEX ix_tentativa_usuario ON tentativa (id_usuario);
CREATE INDEX ix_tentativa_pergunta ON tentativa (id_pergunta);
CREATE INDEX ix_pergunta_fonte_fonte ON pergunta_fonte (id_fonte);
